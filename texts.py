def norm_name(value: str) -> str:
    """Tuman nomini solishtirish uchun: harflardan boshqasini olib tashlaydi."""
    v = (value or "").lower()
    v = re.sub(r"[ʻʼ’‘`´']", "", v)  # o'/g' kabi apostrof belgilari
    v = re.sub(r"(tumani|tuman|район|rayon|district)", "", v)
    return re.sub(r"[\W\d_]+", "", v)


